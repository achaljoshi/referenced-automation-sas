#!/usr/bin/env node
import * as fs from 'node:fs';
import * as path from 'node:path';
import { decodeScript, importEgScript } from '../egScript';
import { DEFAULT_TAG, DEFAULT_TEST_IMPORT } from '../generator';
import type { CliIo } from './convert';

export const IMPORT_USAGE = `sas-eg-import-script - turn the script of File > Schedule Project into a test

Enterprise Guide writes a VBScript (File > Schedule Project) that opens a project, runs it, saves and quits, through its automation object model.
This reads it (or a PowerShell script of the same shape) and writes a test that does the same with the framework's Enterprise Guide COM driver.

  sas-eg-import-script <file.vbs | file.ps1 | folder> [options]

Options:
  --out <file.ts|folder>   Where to write the test: a .ts file name, or a folder (created if needed). Default: tests/desktop-generated.
  --test-import <module>   Module desktopTest (as test) and desktopExpect (as expect) come from. Default: ${DEFAULT_TEST_IMPORT}.
  --desktop-import <mod>   Module that exports SasEnterpriseGuide by that name (for example ../../src/desktop). Default: the \`desktop\` namespace of the package root.
  --session-fixture <name> The fixture that provides the DesktopSession. Default: desktopSession.
  --tag <tag>              Tag added to the test title. Default: ${DEFAULT_TAG}.
  --name <text>            Base name of the test title and file. Default: the script's file name.
  --fail-on-warnings       The test also fails when a program ended with warnings (by default only errors fail it).
  --allow-no-assertion     Leave the failing guard out when the script runs nothing (so there is nothing to check).
  --strict                 Exit 1 if anything needs a human: a script line the importer could not convert (TODO(manual)) or no assertion.
  -h, --help

The profile name and anything that looks like a password are never written into the test: they are read from the environment (SAS_EG_PROFILE, SAS_PASSWORD ...).
NOT VERIFIED against a script generated by your Enterprise Guide: see docs/RECORD_AND_PLAY.md.
`;

interface Options {
  input: string;
  out: string;
  testImport?: string;
  desktopImport?: string;
  sessionFixture?: string;
  tag?: string;
  name?: string;
  failOnWarnings: boolean;
  allowNoAssertion: boolean;
  strict: boolean;
}

function parseArgs(argv: string[]): Options {
  const opts: Options = { input: '', out: '', failOnWarnings: false, allowNoAssertion: false, strict: false };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i] as string;
    const value = () => {
      const next = argv[++i];
      if (next === undefined) throw new Error(`${arg} needs a value`);
      return next;
    };
    if (arg === '--out') opts.out = value();
    else if (arg === '--test-import') opts.testImport = value();
    else if (arg === '--desktop-import') opts.desktopImport = value();
    else if (arg === '--session-fixture') opts.sessionFixture = value();
    else if (arg === '--tag') opts.tag = value();
    else if (arg === '--name') opts.name = value();
    else if (arg === '--fail-on-warnings') opts.failOnWarnings = true;
    else if (arg === '--allow-no-assertion') opts.allowNoAssertion = true;
    else if (arg === '--strict') opts.strict = true;
    else if (arg.startsWith('-')) throw new Error(`unknown option ${arg}`);
    else if (!opts.input) opts.input = arg;
    else throw new Error(`unexpected argument ${arg}`);
  }
  if (!opts.input) throw new Error('missing the script (a .vbs or .ps1 file, or a folder of them)');
  return opts;
}

const stdio: CliIo = { out: (t) => void process.stdout.write(t), err: (t) => void process.stderr.write(t) };

/** The importer as a function. Returns the exit code: 0 done, 1 --strict found something, 2 usage. */
export function runImportCli(argv: string[], io: CliIo = stdio): number {
  if (argv.includes('-h') || argv.includes('--help')) {
    io.out(IMPORT_USAGE);
    return 0;
  }
  let opts: Options;
  try {
    opts = parseArgs(argv);
  } catch (error) {
    io.err(`${(error as Error).message}\n\n${IMPORT_USAGE}`);
    return 2;
  }
  let files: string[];
  try {
    files = fs.statSync(opts.input).isDirectory()
      ? fs
          .readdirSync(opts.input)
          .filter((f) => /\.(vbs|ps1)$/i.test(f))
          .sort()
          .map((f) => path.join(opts.input, f))
      : [opts.input];
  } catch {
    io.err(`${opts.input} does not exist\n`);
    return 2;
  }
  if (files.length === 0) {
    io.err(`no .vbs or .ps1 files in ${opts.input}\n`);
    return 2;
  }
  if (files.length > 1 && opts.name) {
    io.err('--name names one test: give one script, not a folder\n');
    return 2;
  }
  const outDir = opts.out && !opts.out.endsWith('.ts') ? opts.out : opts.out ? path.dirname(opts.out) : 'tests/desktop-generated';
  let attention = 0;
  for (const file of files) {
    const base = path.basename(file).replace(/\.[^.]+$/, '');
    const label = path.relative(process.cwd(), file).replace(/\\/g, '/');
    const result = importEgScript(decodeScript(fs.readFileSync(file)), { ...opts, sourceName: label, name: opts.name ?? base }, file);
    const target = files.length === 1 && opts.out.endsWith('.ts') ? opts.out : path.join(outDir, `${base.replace(/[^A-Za-z0-9_-]+/g, '_')}.spec.ts`);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, result.code);
    io.out(`${label}  ->  ${target}\n`);
    if (result.envVars.length > 0) io.out(`    reads from the environment: ${result.envVars.join(', ')}\n`);
    for (const warning of result.warnings) io.out(`    ${warning.severity === 'todo' ? 'TODO ' : ''}${warning.event !== undefined ? `script line ${warning.event}: ` : ''}${warning.message}\n`);
    if (!result.hasAssertion) io.out(`    no assertion: the script runs nothing, ${opts.allowNoAssertion ? 'add a check (TODO in the file)' : 'so the test fails until you add one'}\n`);
    attention += result.todos;
  }
  if (opts.strict && attention > 0) {
    io.err(`\n${attention} item(s) need attention (--strict).\n`);
    return 1;
  }
  return 0;
}

if (require.main === module) process.exit(runImportCli(process.argv.slice(2)));
