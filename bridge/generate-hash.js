#!/usr/bin/env node
'use strict';
/**
 * Build step: computes the SHA-256 of bridge/sas-desktop-bridge.ps1 and writes it to src/desktop/bridgeHash.generated.ts, the
 * constant the TypeScript side compares the script with before it runs one (a modified or outdated copy is refused).
 *
 *   node bridge/generate-hash.js            write src/desktop/bridgeHash.generated.ts
 *   node bridge/generate-hash.js --check    exit 1 if the file is out of date (CI; run it before `npm run build`)
 *   node bridge/generate-hash.js --print    print the hash only
 *
 * What is hashed: the script text with the byte order mark removed, line endings normalised to LF, an Authenticode signature
 * block ("# SIG # Begin signature block" to the end) cut off and the end trimmed - so signing the approved copy, or git changing
 * its line endings, does not change the hash. The same function lives in src/desktop/bridgeFile.ts (normalizeBridgeText); a test
 * keeps the two identical.
 *
 * Run it after every change to the script, review the script change, and commit both files together. Wire it before the build:
 * "prebuild": "node bridge/generate-hash.js".
 */
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const script = path.resolve(__dirname, 'sas-desktop-bridge.ps1');
const target = path.resolve(__dirname, '..', 'src', 'desktop', 'bridgeHash.generated.ts');

function normalize(text) {
  return text
    .replace(/^\uFEFF/, '')
    .replace(/\r\n/g, '\n')
    .replace(/\n# SIG # Begin signature block(?:\r?\n#[^\n]*)*\s*$/, '')
    .trim();
}

const hash = crypto.createHash('sha256').update(normalize(fs.readFileSync(script, 'utf8')), 'utf8').digest('hex');

const source = `// GENERATED by bridge/generate-hash.js from bridge/sas-desktop-bridge.ps1 - do not edit by hand.
// Re-run \`node bridge/generate-hash.js\` after a reviewed change to the script (the build does it; CI runs it with --check).
export const BRIDGE_SHA256 = '${hash}';
`;

const mode = process.argv[2];
if (mode === '--print') {
  process.stdout.write(`${hash}\n`);
} else if (mode === '--check') {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== source) {
    process.stderr.write(`src/desktop/bridgeHash.generated.ts is out of date: the script hashes to ${hash}. Run: node bridge/generate-hash.js\n`);
    process.exit(1);
  }
  process.stdout.write(`bridge hash OK (${hash})\n`);
} else {
  fs.writeFileSync(target, source);
  process.stdout.write(`wrote ${path.relative(process.cwd(), target)} (${hash})\n`);
}
